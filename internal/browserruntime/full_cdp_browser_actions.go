func summarizeFullCDPDocument(document *html.Node) (string, string,
	[]FullCDPPageElement, bool,
) {
	if document == nil {
		return "", "", []FullCDPPageElement{}, false
	}
	title := ""
	var text strings.Builder
	elements := make([]FullCDPPageElement, 0, 32)
	truncated := false
	var walk func(*html.Node, bool)
	walk = func(node *html.Node, hidden bool) {
		if node == nil {
			return
		}
		if node.Type == html.ElementNode {
			tag := strings.ToLower(node.Data)
			hidden = hidden || tag == "script" || tag == "style" || tag == "noscript" ||
				hasHTMLAttribute(node, "hidden") || strings.EqualFold(htmlAttribute(node, "aria-hidden"), "true")
			if tag == "title" && title == "" {
				title = boundedFullCDPText(nodeText(node), MaxFullCDPPageElementTextRunes)
			}
			if !hidden && isFullCDPInteractiveTag(tag) &&
				len(elements) < MaxFullCDPPageSnapshotElements {
				selector := fullCDPSelector(node)
				if validFullCDPModelSelector(selector) {
					name := htmlAttribute(node, "aria-label")
					if name == "" {
						name = htmlAttribute(node, "title")
					}
					if name == "" {
						name = nodeText(node)
					}
					elements = append(elements, FullCDPPageElement{Selector: selector,
						Tag: tag, Role: boundedFullCDPText(htmlAttribute(node, "role"), 128),
						Name: boundedFullCDPText(name, MaxFullCDPPageElementTextRunes),
						Type: boundedFullCDPText(htmlAttribute(node, "type"), 128),
						Disabled: hasHTMLAttribute(node, "disabled") ||
							strings.EqualFold(htmlAttribute(node, "aria-disabled"), "true")})
				}
			} else if !hidden && isFullCDPInteractiveTag(tag) {
				truncated = true
			}
		}
		if node.Type == html.TextNode && !hidden {
			value := strings.Join(strings.Fields(node.Data), " ")
			if value != "" {
				if text.Len() > 0 {
					text.WriteByte(' ')
				}
				remaining := MaxFullCDPPageSnapshotTextBytes - text.Len()
				if remaining <= 0 {
					truncated = true
				} else if len([]byte(value)) > remaining {
					text.WriteString(trimUTF8Bytes(value, remaining))
					truncated = true
				} else {
					text.WriteString(value)
				}
			}
		}
		for child := node.FirstChild; child != nil; child = child.NextSibling {
			walk(child, hidden)
		}
	}
	walk(document, false)
	return boundedFullCDPText(title, MaxFullCDPPageElementTextRunes),
		boundedFullCDPText(text.String(), MaxFullCDPPageSnapshotTextBytes), elements, truncated
}

func validFullCDPModelSelector(value string) bool {
	if !validUIEvidenceSelector(value) {
		return false
	}
	if strings.HasPrefix(value, "#") {
		return fullCDPSimpleID.MatchString(strings.TrimPrefix(value, "#"))
	}
	parts := strings.Split(value, " > ")
	if len(parts) == 0 || len(parts) > 12 {
		return false
	}
	for _, part := range parts {
		if !fullCDPSelectorPart.MatchString(part) {
			return false
		}
	}
	last := parts[len(parts)-1]
	tag, _, _ := strings.Cut(last, ":")
	return isFullCDPInteractiveTag(tag)
}

func isFullCDPInteractiveTag(tag string) bool {
	switch tag {
	case "a", "button", "input", "select", "textarea", "summary":
		return true
	default:
		return false
	}
}

func fullCDPSelector(node *html.Node) string {
	if id := htmlAttribute(node, "id"); fullCDPSimpleID.MatchString(id) &&
		redact.String(id) == id {
		return "#" + id
	}
	parts := make([]string, 0, 8)
	for current := node; current != nil && current.Type != html.DocumentNode &&
		len(parts) < 12; current = current.Parent {
		if current.Type != html.ElementNode {
			continue
		}
		tag := strings.ToLower(current.Data)
		index := 1
		for sibling := current.PrevSibling; sibling != nil; sibling = sibling.PrevSibling {
			if sibling.Type == html.ElementNode && strings.EqualFold(sibling.Data, current.Data) {
				index++
			}
		}
		parts = append(parts, fmt.Sprintf("%s:nth-of-type(%d)", tag, index))
		if tag == "body" || tag == "html" {
			break
		}
	}
	for left, right := 0, len(parts)-1; left < right; left, right = left+1, right-1 {
		parts[left], parts[right] = parts[right], parts[left]
	}
	return strings.Join(parts, " > ")
}

func nodeText(node *html.Node) string {
	var builder strings.Builder
	var walk func(*html.Node)
	walk = func(current *html.Node) {
		if current == nil {
			return
		}
		if current.Type == html.ElementNode {
			switch strings.ToLower(current.Data) {
			case "script", "style", "noscript":
				return
			}
		}
		if current.Type == html.TextNode {
			if builder.Len() > 0 {
				builder.WriteByte(' ')
			}
			builder.WriteString(current.Data)
		}
		for child := current.FirstChild; child != nil; child = child.NextSibling {
			walk(child)
		}
	}
	walk(node)
	return strings.Join(strings.Fields(builder.String()), " ")
}

func htmlAttribute(node *html.Node, name string) string {
	if node == nil {
		return ""
	}
	for _, attribute := range node.Attr {
		if strings.EqualFold(attribute.Key, name) {
			return strings.TrimSpace(attribute.Val)
		}
	}
	return ""
}

func hasHTMLAttribute(node *html.Node, name string) bool {
	if node == nil {
		return false
	}
	for _, attribute := range node.Attr {
		if strings.EqualFold(attribute.Key, name) {
			return true
		}
	}
	return false
}

func boundedFullCDPText(value string, limit int) string {
	value = strings.TrimSpace(outputsafe.Sanitize([]byte(value)))
	value = redact.String(strings.Join(strings.Fields(value), " "))
	if limit <= 0 {
		return ""
	}
	if utf8.RuneCountInString(value) > limit && limit < MaxFullCDPPageSnapshotTextBytes {
		runes := []rune(value)
		value = string(runes[:limit])
	}
	if len([]byte(value)) > limit && limit >= MaxFullCDPPageSnapshotTextBytes {
		value = trimUTF8Bytes(value, limit)
	}
	return value
}

func trimUTF8Bytes(value string, limit int) string {
	if limit <= 0 {
		return ""
	}
	for len([]byte(value)) > limit {
		_, size := utf8.DecodeLastRuneInString(value)
		value = value[:len(value)-size]
	}
	return value
}
