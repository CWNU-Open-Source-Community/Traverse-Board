const (
	FullCDPPageSnapshotProtocolVersion = "full_cdp_page_snapshot.v1"
	FullCDPInteractionProtocolVersion  = "full_cdp_interaction.v1"
	FullCDPScreenshotProtocolVersion   = "full_cdp_screenshot.v1"
	MaxFullCDPPageSnapshotHTMLBytes    = 1024 * 1024
	MaxFullCDPPageSnapshotTextBytes    = 48 * 1024
	MaxFullCDPPageSnapshotElements     = 256
	MaxFullCDPPageElementTextRunes     = 512
	MaxFullCDPModelInputBytes          = 16 * 1024
	fullCDPSelectorProvenanceTTL       = time.Minute
)

type fullCDPDocumentIdentity struct {
	CanonicalURL string
	FrameID      string
	LoaderID     string
	RootNodeID   int64
	HTMLSHA256   string
}

func (identity fullCDPDocumentIdentity) sameNavigation(other fullCDPDocumentIdentity) bool {
	return identity.CanonicalURL != "" && identity.CanonicalURL == other.CanonicalURL &&
		identity.FrameID != "" && identity.FrameID == other.FrameID &&
		identity.LoaderID != "" && identity.LoaderID == other.LoaderID &&
		identity.RootNodeID > 0 && identity.RootNodeID == other.RootNodeID
}

func (identity fullCDPDocumentIdentity) sameExact(other fullCDPDocumentIdentity) bool {
	return identity.sameNavigation(other) && identity.HTMLSHA256 != "" &&
		identity.HTMLSHA256 == other.HTMLSHA256
}

